"""Builds COVERAGE.md: every test case in qa-review-*.md with its Maestro flow
or the reason it has none. Run: python3 -I maestro/coverage.py (from qa/)."""
import glob, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
review = sorted(glob.glob(os.path.join(here, '..', 'qa', 'qa-review-v*.md')))[-1]

flows = {}
for path in sorted(glob.glob(os.path.join(here, 'flows', '**', '*.yaml'), recursive=True) + glob.glob(os.path.join(here, 'qa-testcases', '*.yaml'))):
    m = re.search(r'^tags:\s*\[(.*)\]', open(path).read(), re.M)
    for tag in (m.group(1).split(',') if m else []):
        tag = tag.strip()
        if re.fullmatch(r'[A-Z0-9]+-\d+', tag):
            flows.setdefault(tag, []).append(os.path.relpath(path, here))

rows, section = [], ''
for line in open(review, encoding='utf-8'):
    if line.startswith('### 3.'):
        section = line[4:].strip()
    m = re.match(r'^\| (\[.\]) \| ([A-Z0-9]+-\d+) \| ([^|]+)\|', line)
    if not m:
        continue
    status, cid, scenario = m.group(1), m.group(2), m.group(3).strip()
    cells = [c.strip() for c in line.split('|')]
    steps, expected = cells[6], cells[7]
    if cid in flows:
        how = 'Maestro: ' + ', '.join(f'`{f}`' for f in flows[cid])
    elif 'BLOCKED' in expected:
        how = 'Blocked: ' + re.search(r'BLOCKED[^\]]*', expected).group(0)
    elif re.search(r'[Cc]apture|request|`\w+`\s*=', steps + expected):
        how = 'Request check from the app log (Maestro cannot read network)'
    else:
        how = 'Not automated yet'
    rows.append((section, status, cid, scenario, how))

auto = sum(1 for r in rows if r[4].startswith('Maestro'))
out = [f'# Maestro coverage — {os.path.basename(review)}', '',
       'Generated by `maestro/coverage.py`; do not edit by hand.', '',
       f'{auto} of {len(rows)} test cases have a Maestro flow.', '']
current = None
for section, status, cid, scenario, how in rows:
    if section != current:
        out += ['', f'## {section}', '', '| Status | ID | Scenario | Automation |', '|---|---|---|---|']
        current = section
    out.append(f'| {status} | {cid} | {scenario} | {how} |')
open(os.path.join(here, 'COVERAGE.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{auto}/{len(rows)} automated')
