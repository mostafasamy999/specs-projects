"""Shows which QA files are behind the changelog.

Every changelog entry has a number (## CL-n · ...). The QA review records
`**Synced to changelog:** CL-n` and every Maestro flow `# synced: CL-n`: the
last change it was checked against. This script lists anything behind the
newest entry, with the changes it hasn't absorbed, and writes sync-status.md.

Run from anywhere: python3 -I qa/sync_check.py
Exit code 1 when something is behind (usable in CI or a git hook).
"""
import glob
import os
import re
import sys

QA = os.path.dirname(os.path.abspath(__file__))
CHANGELOG = os.path.join(QA, '..', 'changelog.md')


def read_changes():
    changes = {}
    text = open(CHANGELOG, encoding='utf-8').read()
    for m in re.finditer(r'^## CL-(\d+) · (.+)$', text, re.M):
        body = text[m.end():].split('\n## ', 1)[0]
        impact = re.search(r'\*\*QA impact:\*\*\s*(.+)', body)
        changes[int(m.group(1))] = (m.group(2).strip(),
                                    impact.group(1).strip() if impact else 'not stated')
    return changes


def synced(path, pattern):
    m = re.search(pattern, open(path, encoding='utf-8').read(), re.M)
    return int(m.group(1)) if m else 0


def main():
    changes = read_changes()
    latest = max(changes)
    items = []
    for path in sorted(glob.glob(os.path.join(QA, 'qa-review-v*.md'))):
        items.append(('Test cases', os.path.basename(path),
                      synced(path, r'\*\*Synced to changelog:\*\*\s*CL-(\d+)')))
    for path in sorted(glob.glob(os.path.join(QA, 'maestro', '**', '*.yaml'), recursive=True)):
        rel = os.path.relpath(path, os.path.join(QA, 'maestro'))
        if rel == 'config.yaml':
            continue
        items.append(('Maestro', rel, synced(path, r'^# synced: CL-(\d+)')))

    behind = [i for i in items if i[2] < latest]
    lines = ['# QA sync status', '',
             'Generated by `qa/sync_check.py`; do not edit by hand.', '',
             f'Newest changelog entry: **CL-{latest}** · {changes[latest][0]}', '']
    for kind in ('Test cases', 'Maestro'):
        group = [i for i in items if i[0] == kind]
        late = [i for i in group if i[2] < latest]
        mark = '✅ up to date' if not late else f'⚠️ {len(late)} of {len(group)} behind'
        oldest = min((i[2] for i in group), default=latest)
        lines.append(f'- **{kind}:** {mark} (oldest synced: CL-{oldest})')
    lines.append('')

    if behind:
        lines += ['## Behind', '', '| Kind | File | Synced to | Missing changes |', '|---|---|---|---|']
        for kind, name, n in behind:
            missing = ', '.join(f'CL-{c}' for c in range(n + 1, latest + 1))
            lines.append(f'| {kind} | `{name}` | {"CL-%d" % n if n else "none"} | {missing} |')
        missing_ids = sorted({c for _, _, n in behind for c in range(n + 1, latest + 1)})
        lines += ['', '## Changes to apply', '']
        for c in missing_ids:
            title, impact = changes[c]
            lines.append(f'- **CL-{c}** · {title}. QA impact: {impact}')
        lines += ['', 'After checking a file against these changes (and updating it if needed), '
                  'set its marker to the newest CL and run this script again.']
    else:
        lines += ['Everything is synced to the newest changelog entry.']

    open(os.path.join(QA, 'sync-status.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('\n'.join(l for l in lines[4:] if l.startswith(('Newest', '- **'))))
    if behind:
        print(f'{len(behind)} file(s) behind CL-{latest}; see qa/sync-status.md')
    return 1 if behind else 0


if __name__ == '__main__':
    sys.exit(main())
